#!/usr/bin/env bash
# Regenerate pkg/video/cvi/types_linux.go from the CVITek uapi headers.
#
#   tools/gen-cvi-types.sh [path-to-nanokvm-build]
#
# The headers live in the BSP repo (meta-sophgo/recipes-kernel/soph-media),
# not here, and generating needs the Yocto riscv64 cross toolchain that the
# BSP build produces. That is why the output is checked in: an ordinary
# `go build` needs none of this.
#
# Run this after bumping the vendored soph-media sources, and commit the diff.

set -euo pipefail

BSP="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../nanokvm-build" && pwd)}"
OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/pkg/video/cvi"

die() { echo "gen-cvi-types: error: $*" >&2; exit 1; }

UAPI="${BSP}/meta-sophgo/recipes-kernel/soph-media/files/soph-media/include"
[ -d "${UAPI}" ] || die "CVITek headers not found under ${UAPI}
pass the path to the nanokvm-build checkout as \$1"

TC="${BSP}/build/tmp-musl/sysroots-components/x86_64"
CC="${TC}/gcc-cross-riscv64/usr/bin/riscv64-oe-linux-musl/riscv64-oe-linux-musl-gcc"
BINUTILS="${TC}/binutils-cross-riscv64/usr/bin/riscv64-oe-linux-musl"
[ -x "${CC}" ] || die "riscv64 cross gcc not found at ${CC}
run 'kas build kas.yml' in ${BSP} first"

# musl headers (pthread.h, stdio.h) come from any riscv64 recipe sysroot; the
# server's is the one guaranteed to exist in a build that produced this app.
SYSROOT=$(ls -d "${BSP}"/build/tmp-musl/work/riscv64-oe-linux-musl/nanokvm-server/*/recipe-sysroot 2>/dev/null | head -1)
[ -n "${SYSROOT}" ] || die "no riscv64 recipe-sysroot found under ${BSP}/build"

# gcc resolves the assembler by the bare name "as", but the cross binutils are
# installed with a riscv64-oe-linux-musl- prefix, so -B alone does not find
# them and gcc silently falls back to the host assembler -- which then rejects
# gcc's own -march=rv64imafdc_zicsr_zifencei. Give it a directory of
# unprefixed symlinks to point -B at.
SHIM=$(mktemp -d)
trap 'rm -rf "${SHIM}"' EXIT
for t in as ld ar nm objcopy objdump ranlib strip; do
    ln -sf "${BINUTILS}/riscv64-oe-linux-musl-${t}" "${SHIM}/${t}"
done

# NB: the compiler flags go after "--" (see `go tool cgo -h`: "cgo --
# [compiler options] file.go"). CGO_CFLAGS is NOT consulted when cgo is invoked
# directly like this -- only through `go build` -- so passing them that way
# silently drops the sysroot and the build dies on <string.h>.
# -objdir keeps cgo's scratch files out of the package directory. Without it
# cgo writes _obj/ and a _cgo_2.o (a ~68K riscv64 object) straight into
# pkg/video/cvi, where nothing gitignores them and `git add pkg/video/` would
# commit them. Point it at the temp dir the trap already cleans up.
cd "${OUT}"
rm -rf _obj _cgo_*.o                     # left behind by earlier runs of this script
GOOS=linux GOARCH=riscv64 CGO_ENABLED=1 CC="${CC}" \
    go tool cgo -godefs -objdir "${SHIM}/obj" -- \
        "-B${SHIM}" "--sysroot=${SYSROOT}" -D__CV181X__ \
        "-I${UAPI}/common/uapi" "-I${UAPI}/chip/cv181x/uapi" \
        gen_types.go > types_linux.go.tmp

# cgo -godefs emits a "Created by cgo -godefs - DO NOT EDIT" banner but no
# build tag or package doc; prepend our own header so the file reads like the
# rest of the tree and gofmt/lint are happy.
{
    echo "// Code generated by tools/gen-cvi-types.sh; DO NOT EDIT."
    echo "//"
    echo "// Struct layouts for the CVITek multimedia uapi, generated from the vendor"
    echo "// headers in meta-sophgo/recipes-kernel/soph-media against the riscv64 cross"
    echo "// toolchain. See gen_types.go for what is generated and why."
    echo
    # Drop cgo's own banner and the "// cgo -godefs -- ..." echo of the command
    # line: the latter embeds this machine's checkout paths and the mktemp
    # assembler-shim directory, which changes every run and would make the
    # generated file differ on every regeneration for no real reason.
    # Match the whole "// cgo -godefs ..." line however it is spelled -- it
    # echoes the full invocation, including this machine's checkout paths and
    # the mktemp scratch dir, so leaving it in makes every regeneration
    # produce a spurious diff. (Anchoring on "-godefs --" specifically is what
    # broke when -objdir was added between them.)
    grep -v '^// Code generated by cmd/cgo -godefs' types_linux.go.tmp \
        | grep -v '^// cgo -godefs'
} > types_linux.go
rm -f types_linux.go.tmp

gofmt -w types_linux.go
echo "gen-cvi-types: wrote ${OUT}/types_linux.go"
